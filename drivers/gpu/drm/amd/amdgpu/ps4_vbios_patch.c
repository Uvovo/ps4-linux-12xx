/*
 * PS4 VBIOS in-memory patch for Belize (CUH-2xxx) and Gladius (CUH-7xxx)
 *
 * Problem: Sony stripped the DIGTransmitterInfo data table from the Slim/Pro
 * VBIOS images (reduced to a 4-byte stub). The UNIPHYTransmitterControl
 * command table bytecode is identical to the Fat models, but when it executes
 * ATOM_TRANSMITTER_ACTION_SETUP_VSEMPH it reads voltage swing / pre-emphasis
 * values from the empty DIGTransmitterInfo table, resulting in incorrect PHY
 * programming. This causes DP link training failures with many monitors.
 *
 * Fix: After the VBIOS is loaded from VRAM into adev->bios, detect the stub
 * DIGTransmitterInfo and graft the known-good table from the Fat (ThP/CUH-12xx)
 * VBIOS into free space at the end of the 64KB image, then update the Master
 * Data Table pointer.
 *
 * The Fat's DIGTransmitterInfo (488 bytes, format 3.1) contains:
 *   - DP voltage swing / pre-emphasis settings for all 16 VS/PE combinations
 *   - PHY PLL register lists and settings for RBR/HBR/HBR2 link rates
 *   - PHY analog configuration
 *
 * Copyright (C) 2026 Armandas Kvietkus
 */

