#define DIG_TRANSMITTER_INFO_IDX	7
#define MDT_ENTRY_OFFSET(idx)		(4 + (idx) * 2)
#define VBIOS_IMAGE_SIZE		65536
#define DIG_TABLE_PLACEMENT		(VBIOS_IMAGE_SIZE - sizeof(ps4_dig_transmitter_info))

/**
 * ps4_vbios_patch_dig_transmitter_info - Patch Belize/Gladius VBIOS in memory
 * @adev: amdgpu_device pointer (bios already loaded)
 *
 * Detects the 4-byte DIGTransmitterInfo stub on Slim/Pro VBIOS images and
 * replaces it with the full table from the Fat model. The table is placed
 * in the zero-padded free space at the end of the 64KB VBIOS image.
 *
 * Must be called after adev->bios is populated but before amdgpu_atom_parse().
 */
void ps4_vbios_patch_dig_transmitter_info(struct amdgpu_device *adev)
{
	u8 *bios = adev->bios;
	u16 atom_hdr_ptr, data_tbl_off, mdt_off;
	u16 dig_off, dig_size;
	u16 new_offset;

	if (!bios || adev->bios_size < VBIOS_IMAGE_SIZE)
		return;

	if (adev->pdev->device != 0x9923 && adev->pdev->device != 0x9924)
		return;

	/* Validate ATOMBIOS header */
	if (bios[0] != 0x55 || bios[1] != 0xAA)
		return;

	atom_hdr_ptr = le16_to_cpup((__le16 *)&bios[0x48]);
	if (atom_hdr_ptr + 0x22 >= adev->bios_size)
		return;
	if (memcmp(&bios[atom_hdr_ptr + 4], "ATOM", 4) != 0)
		return;

	/* Master Data Table offset (from ATOM_ROM_HEADER + 0x20) */
	data_tbl_off = le16_to_cpup((__le16 *)&bios[atom_hdr_ptr + 0x20]);
	mdt_off = data_tbl_off + MDT_ENTRY_OFFSET(DIG_TRANSMITTER_INFO_IDX);
	if (mdt_off + 2 >= adev->bios_size)
		return;

	/* Read current DIGTransmitterInfo pointer */
	dig_off = le16_to_cpup((__le16 *)&bios[mdt_off]);
	if (!dig_off || dig_off + 4 > adev->bios_size)
		return;

	dig_size = le16_to_cpup((__le16 *)&bios[dig_off]);
	if (dig_size > 4) {
		/* Table already populated — nothing to do */
		return;
	}

	/* Place the Fat's table at the end of the image */
	new_offset = DIG_TABLE_PLACEMENT;
	if (new_offset + sizeof(ps4_dig_transmitter_info) > adev->bios_size)
		return;

	/* Verify destination is free (should be zero-padded) */
	if (bios[new_offset] != 0x00) {
		dev_warn(adev->dev,
			 "ps4_vbios_patch: destination not free at 0x%x, skipping\n",
			 new_offset);
		return;
	}

	/* Copy the table */
	memcpy(&bios[new_offset], ps4_dig_transmitter_info,
	       sizeof(ps4_dig_transmitter_info));

	/* Update the MDT pointer */
	*(__le16 *)&bios[mdt_off] = cpu_to_le16(new_offset);

	dev_info(adev->dev,
		 "ps4_vbios_patch: injected DIGTransmitterInfo (%zu bytes) at 0x%x for DID 0x%04x\n",
		 sizeof(ps4_dig_transmitter_info), new_offset, adev->pdev->device);
}
